-- V3: kho từ vựng theo cấp độ A1–C2 (dùng chung cho mọi user) + cấp độ đang học của user

CREATE TABLE VOCAB_LIBRARY (
    ID              NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LEVEL_CODE      VARCHAR2(2 CHAR)    NOT NULL,
    WORD            VARCHAR2(100 CHAR)  NOT NULL,
    PART_OF_SPEECH  VARCHAR2(50 CHAR)   NOT NULL,
    PHONETIC        VARCHAR2(100 CHAR),
    MEANING         VARCHAR2(1000 CHAR) NOT NULL,
    CONSTRAINT CK_VOCAB_LIBRARY_LEVEL CHECK (LEVEL_CODE IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2'))
);
CREATE INDEX IX_VOCAB_LIBRARY_LEVEL ON VOCAB_LIBRARY (LEVEL_CODE, ID);

-- Cấp độ user đang học; NULL = học từ trong kho tự thêm
ALTER TABLE USERS ADD STUDY_LEVEL VARCHAR2(2 CHAR);
ALTER TABLE USERS ADD CONSTRAINT CK_USERS_STUDY_LEVEL
    CHECK (STUDY_LEVEL IS NULL OR STUDY_LEVEL IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2'));

-- Từ được chép từ kho cấp độ vào kho của user (để tính tiến độ theo cấp độ)
ALTER TABLE WORDS ADD LIBRARY_ID NUMBER(19);
ALTER TABLE WORDS ADD CONSTRAINT FK_WORDS_LIBRARY
    FOREIGN KEY (LIBRARY_ID) REFERENCES VOCAB_LIBRARY (ID) ON DELETE SET NULL;
CREATE INDEX IX_WORDS_USER_LIBRARY ON WORDS (USER_ID, LIBRARY_ID);
