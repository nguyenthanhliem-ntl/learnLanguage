-- V5: multi-language support. Every word and level entry belongs to one language ('en' English, 'ko' Korean, ...).
-- Adding a language later only needs a row in LANGUAGES plus its level data, no schema change.

CREATE TABLE LANGUAGES (
    CODE            VARCHAR2(5 CHAR)    PRIMARY KEY,
    NAME            VARCHAR2(50 CHAR)   NOT NULL
);
INSERT INTO LANGUAGES (CODE, NAME) VALUES ('en', 'English');
INSERT INTO LANGUAGES (CODE, NAME) VALUES ('ko', 'Korean');

-- Existing data is all English
ALTER TABLE WORDS ADD (LANGUAGE_CODE VARCHAR2(5 CHAR) DEFAULT 'en' NOT NULL);
ALTER TABLE WORDS ADD CONSTRAINT FK_WORDS_LANGUAGE FOREIGN KEY (LANGUAGE_CODE) REFERENCES LANGUAGES (CODE);

ALTER TABLE VOCAB_LIBRARY ADD (LANGUAGE_CODE VARCHAR2(5 CHAR) DEFAULT 'en' NOT NULL);
ALTER TABLE VOCAB_LIBRARY ADD CONSTRAINT FK_VOCAB_LIBRARY_LANGUAGE FOREIGN KEY (LANGUAGE_CODE) REFERENCES LANGUAGES (CODE);

-- Level codes depend on the language (CEFR A1–C2, TOPIK1–TOPIK6, ...), validated by the app
ALTER TABLE VOCAB_LIBRARY DROP CONSTRAINT CK_VOCAB_LIBRARY_LEVEL;
ALTER TABLE VOCAB_LIBRARY MODIFY (LEVEL_CODE VARCHAR2(10 CHAR));
DROP INDEX IX_VOCAB_LIBRARY_LEVEL;
CREATE INDEX IX_VOCAB_LIBRARY_LEVEL ON VOCAB_LIBRARY (LANGUAGE_CODE, LEVEL_CODE, ID);

-- Duplicate entries are checked within one language
DROP INDEX UX_WORDS_USER_ENTRY;
CREATE UNIQUE INDEX UX_WORDS_USER_ENTRY ON WORDS (
    USER_ID,
    LANGUAGE_CODE,
    LOWER(TRIM(WORD)),
    LOWER(TRIM(PART_OF_SPEECH)),
    LOWER(TRIM(PHONETIC)),
    LOWER(TRIM(MEANING))
);
DROP INDEX IX_WORDS_USER_WORD;
CREATE INDEX IX_WORDS_USER_WORD ON WORDS (USER_ID, LANGUAGE_CODE, LOWER(TRIM(WORD)));

-- Level being studied, per user and language (no row / NULL = study from the self-added bank)
CREATE TABLE USER_LANGUAGE_SETTINGS (
    USER_ID         NUMBER(19)          NOT NULL,
    LANGUAGE_CODE   VARCHAR2(5 CHAR)    NOT NULL,
    STUDY_LEVEL     VARCHAR2(10 CHAR),
    CONSTRAINT PK_USER_LANGUAGE_SETTINGS PRIMARY KEY (USER_ID, LANGUAGE_CODE),
    CONSTRAINT FK_ULS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_ULS_LANGUAGE FOREIGN KEY (LANGUAGE_CODE) REFERENCES LANGUAGES (CODE)
);

INSERT INTO USER_LANGUAGE_SETTINGS (USER_ID, LANGUAGE_CODE, STUDY_LEVEL)
SELECT ID, 'en', STUDY_LEVEL FROM USERS WHERE STUDY_LEVEL IS NOT NULL;

ALTER TABLE USERS DROP CONSTRAINT CK_USERS_STUDY_LEVEL;
ALTER TABLE USERS DROP COLUMN STUDY_LEVEL;
