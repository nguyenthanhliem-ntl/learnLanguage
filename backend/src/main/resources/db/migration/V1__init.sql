-- V1: schema khởi tạo cho VocabMaster (Oracle 23ai)

CREATE TABLE USERS (
    ID              NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME        VARCHAR2(50 CHAR)   NOT NULL,
    PASSWORD_HASH   VARCHAR2(100 CHAR)  NOT NULL,
    DAILY_GOAL      NUMBER(3)           DEFAULT 20 NOT NULL,
    CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CK_USERS_DAILY_GOAL CHECK (DAILY_GOAL IN (10, 20, 30, 50))
);

CREATE TABLE WORDS (
    ID              NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(19)          NOT NULL,
    WORD            VARCHAR2(100 CHAR)  NOT NULL,
    PHONETIC        VARCHAR2(100 CHAR),
    MEANING         VARCHAR2(1000 CHAR) NOT NULL,
    CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_WORDS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
);

-- Không cho trùng từ trong kho của cùng một user (so sánh lower(trim(word)))
CREATE UNIQUE INDEX UX_WORDS_USER_WORD ON WORDS (USER_ID, LOWER(TRIM(WORD)));
-- Lấy từ theo thứ tự thêm vào
CREATE INDEX IX_WORDS_USER_ID ON WORDS (USER_ID, ID);

CREATE TABLE USER_WORD_PROGRESS (
    ID                NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID           NUMBER(19)        NOT NULL,
    WORD_ID           NUMBER(19)        NOT NULL,
    STATUS            VARCHAR2(10 CHAR) DEFAULT 'NEW' NOT NULL,
    EASE_FACTOR       NUMBER(4,2)       DEFAULT 2.5 NOT NULL,
    INTERVAL_DAYS     NUMBER(5)         DEFAULT 0 NOT NULL,
    REPETITIONS       NUMBER(5)         DEFAULT 0 NOT NULL,
    NEXT_REVIEW_DATE  DATE,
    LAST_REVIEWED_AT  TIMESTAMP,
    CORRECT_COUNT     NUMBER(7)         DEFAULT 0 NOT NULL,
    WRONG_COUNT       NUMBER(7)         DEFAULT 0 NOT NULL,
    CONSTRAINT FK_UWP_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_UWP_WORD FOREIGN KEY (WORD_ID) REFERENCES WORDS (ID) ON DELETE CASCADE,
    CONSTRAINT UK_UWP_USER_WORD UNIQUE (USER_ID, WORD_ID),
    CONSTRAINT CK_UWP_STATUS CHECK (STATUS IN ('NEW', 'LEARNING', 'REVIEW', 'MASTERED'))
);

CREATE INDEX IX_UWP_USER_ID ON USER_WORD_PROGRESS (USER_ID);
CREATE INDEX IX_UWP_USER_NEXT_REVIEW ON USER_WORD_PROGRESS (USER_ID, NEXT_REVIEW_DATE);
CREATE INDEX IX_UWP_USER_STATUS ON USER_WORD_PROGRESS (USER_ID, STATUS);
CREATE INDEX IX_UWP_WORD_ID ON USER_WORD_PROGRESS (WORD_ID);

CREATE TABLE STUDY_LOG (
    ID              NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER(19)          NOT NULL,
    WORD_ID         NUMBER(19)          NOT NULL,
    ACTIVITY_TYPE   VARCHAR2(10 CHAR)   NOT NULL,
    IS_CORRECT      BOOLEAN,
    CREATED_AT      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_LOG_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_LOG_WORD FOREIGN KEY (WORD_ID) REFERENCES WORDS (ID) ON DELETE CASCADE,
    CONSTRAINT CK_LOG_ACTIVITY CHECK (ACTIVITY_TYPE IN ('LEARN', 'QUIZ', 'LISTEN'))
);

-- Thống kê theo ngày và streak
CREATE INDEX IX_LOG_USER_CREATED ON STUDY_LOG (USER_ID, CREATED_AT);
CREATE INDEX IX_LOG_WORD_ID ON STUDY_LOG (WORD_ID);
